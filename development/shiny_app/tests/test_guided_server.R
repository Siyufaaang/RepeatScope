source('development/shiny_app/R/bootstrap.R');require_dependencies();library(shiny)
source(file.path(rs_app_dir,'R/ui.R'));source(file.path(rs_app_dir,'R/server.R'))
check<-function(ok,msg){if(!isTRUE(ok))stop('FAIL: ',msg);cat('PASS:',msg,'\n')}
html<-htmltools::renderTags(rs_ui())$html
check(grepl('try_workflow',html) && grepl('workflow_progress',html),'landing Try and progress are rendered')
check(!grepl('id="hier_enabled"',html) && !grepl('id="create_review"',html),'experimental and manual variants are deferred from the v1 surface')
check(grepl('forward-help',html) && grepl('plate_file-help',html) && grepl('Required',html),'input guidance is adjacent to actual fields')
check(!grepl('<details[^>]* open',html),'advanced panels start closed')
testServer(rs_server,{
  session$setInputs(try_workflow=1);check(rv$step==1,'Try begins at import')
  session$setInputs(workflow_next=1);check(rv$step==1,'incomplete import blocks Next on server')
  session$setInputs(load_demo=1);check(rv$step==2,'demo enters plate review')
  project_before_home<-object_hash(rv$p)
  session$setInputs(home_section=list(section='how-it-works',nonce=1))
  check(rv$step==0 && object_hash(rv$p)==project_before_home,'home navigation preserves the complete working project')
  session$setInputs(edit_layout=1)
  check(rv$step==2 && object_hash(rv$p)==project_before_home,'returning to Arrange plate preserves the working project')
  session$setInputs(workflow_next=2);check(rv$step==3,'layout advances without a confirmation checkbox')
  session$setInputs(workflow_next=4);check(rv$step==4,'imported peaks advance to reference')
  session$setInputs(forward='TTATGCGA',reverse='ACGGTCAA',forward_tail='',reverse_tail='',motif='CAG')
  session$elapse(700);session$setInputs(workflow_next=5)
  check(rv$step==5,'complete matching inputs advance directly to Results')
  check(grepl('Reverse primer',output$structure_diagram$html),'structure diagram renders on the combined page')
  session$setInputs(workflow_back=1);check(rv$step==4,'Back returns without resetting input')
  session$setInputs(forward='TTATGCGT',workflow_next=6);check(rv$step==4,'changed primer immediately blocks reuse of old match')
  session$elapse(700);check(rv$amplicon$status=='unsupported','automatic matching surfaces the mismatch')
  session$setInputs(forward='TTATGCGA');session$elapse(700)
  check(rv$amplicon$status=='located' && is.null(rv$p$structure),'automatic exact match gives a draft, not a false confirmation')
  session$setInputs(workflow_next=7);check(rv$step==5,'unconfirmed structure can continue to Results')
  session$setInputs(run_analysis=1);check(all(is.na(results()$EI)),'continuing does not bypass formal assay eligibility')
  session$setInputs(workflow_back=2);session$setInputs(tract_start=9,tract_end=59,counting_rule='motif_only')
  check(rv$p$reference_draft$counting_rule=='motif_only','advanced draft edits are saved without requiring confirmation')
  session$setInputs(forward='')
  check(is.null(rv$p$structure) && rv$p$assay$status=='unconfigured' && rv$p$reference_draft$amplicon$forward=='','clearing a primer immediately persists the incomplete draft and removes confirmation')
  session$elapse(700);check(rv$p$reference_draft$amplicon$status=='incomplete','incomplete input remains visibly and persistently incomplete')
  session$setInputs(load_demo=2);session$setInputs(layout_reviewed=TRUE,workflow_next=9)
  original_peaks<-object_hash(rv$p$peaks)
  peak_path<-file.path(rs_app_dir,'examples/SYNTHETIC_peaks.csv')
  session$setInputs(peak_file=data.frame(name='replacement.csv',size=file.info(peak_path)$size,datapath=peak_path,type='text/csv'),workflow_next=10)
  check(rv$step==3 && object_hash(rv$p$peaks)==original_peaks,'new file selection blocks Next until that file is imported')
  session$setInputs(preview_peaks=1)
  session$setInputs(peak_range='changed before import',map_Size='',commit_peaks=1)
  check(object_hash(rv$p$peaks)==original_peaks && is.null(rv$peak_committed_key),'an incomplete mapping cannot replace the previously committed peaks')
})
cat('GUIDED SERVER SUITE PASS\n')
