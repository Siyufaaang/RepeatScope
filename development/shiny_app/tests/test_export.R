source('development/shiny_app/tests/helper.R');load_module('reference');load_module('engine');load_module('report');load_module('synthetic')
check(exists('read_source_table') && exists('write_report_bundle'),'portable import/export is implemented')
dir<-tempfile('rs-export-');dir.create(dir)
m<-matrix('',8,12);m[1,1]<-'001';m[8,12]<-'009'
file<-file.path(dir,'plate.xlsx');writexl::write_xlsx(list(Plate=as.data.frame(m)),file,col_names=FALSE)
pl<-plate_from_matrix(read_source_table(file,'xlsx',sheet='Plate',range='A1:L8',header=FALSE))
check(identical(pl$Code[c(1,96)],c('001','009')),'Excel text IDs survive file round-trip')
file2<-file.path(dir,'input.csv');writeLines('Well,Size,Height,Code\nA01,200,1000,001',file2)
check(read_source_table(file2,'csv')$Code[1]=='001','CSV text IDs are not coerced to numbers')
p<-synthetic_project();p<-fit_project(p);p$threshold<-.2;p$window<-'extended'
out<-file.path(dir,'test.repeatscope.rds');save_project(p,out);q<-read_project(out)
check(identical(p,q) && !fit_is_stale(q),'project restores inputs, config, metadata, fitted models and current threshold')
q$peaks$Height[1]<-q$peaks$Height[1]+1;save_project(q,out);qq<-read_project(out)
check(fit_is_stale(qq),'restored stale results stay stale')
bad<-p;bad$schema<-'unknown';saveRDS(bad,out)
check(fails(read_project(out)),'unsupported project schema is rejected')
p$originals<-list(list(name='../private.txt',bytes=charToRaw('uploaded text')))
archive<-file.path(dir,'report.zip');write_report_bundle(p,archive)
names<-utils::unzip(archive,list=TRUE)$Name
check(!any(grepl('originals',names)) && all(c('results_long.csv','EI_comparison.csv','manifest.json','EI_overview.svg','EI_overview.pdf','EI_overview.png')%in%names),'report contains figures and long/wide tables but omits originals by default')
utils::unzip(archive,exdir=file.path(dir,'readback'))
rr<-read.csv(file.path(dir,'readback/results_long.csv'));screen<-threshold_results(p)
check(near(rr$Threshold,rep(.2,nrow(rr))) && identical(rr$Status,screen$Status) && near(rr$EI,screen$EI),'export threshold/status/NA and EI equal current view')
write_report_bundle(p,archive,include_originals=TRUE)
check(any(grepl('originals/001_private.txt',utils::unzip(archive,list=TRUE)$Name,fixed=TRUE)),'explicit original inclusion sanitizes filename paths')
id<-p$records$Record_ID[1];p<-create_reviewed(p,id,p$fit$records[[id]]$modal_id,reason='Synthetic re-evaluation',evidence='Synthetic calibration record')
write_report_bundle(p,archive,variant='reviewed-1');utils::unzip(archive,exdir=file.path(dir,'reviewed'))
manifest<-jsonlite::read_json(file.path(dir,'reviewed/manifest.json'))
reviewed<-read.csv(file.path(dir,'reviewed/results_long.csv'))
check(manifest$run_id=='reviewed-1' && nzchar(manifest$review$evidence) && all(reviewed$Run_ID=='reviewed-1'),'reviewed ZIP manifest and tables identify the selected reviewed run')
empty<-file.path(dir,'empty.zip');write_report_bundle(new_project(),empty)
check(file.exists(empty),'draft project can export a documented empty report')
draft<-new_project();draft$reference<-p$reference;draft$reference_draft<-p$structure;draft['structure']<-list(NULL)
draft$reference_draft$status<-'preview';draft$reference_draft$confirmed_at<-NULL
write_report_bundle(draft,empty);utils::unzip(empty,exdir=file.path(dir,'draft-preview'))
manifest<-jsonlite::read_json(file.path(dir,'draft-preview/manifest.json'))
svg<-paste(readLines(file.path(dir,'draft-preview/reference_structure.svg')),collapse='')
check(is.null(manifest$structure) && !is.null(manifest$reference_draft) && grepl('UNCONFIRMED',svg),'report exports an unconfirmed preview without promoting scientific confirmation')
cat('EXPORT SUITE PASS\n')
