source('development/shiny_app/R/bootstrap.R');require_dependencies()
library(shiny)
if(file.exists(file.path(rs_app_dir,'R/server.R')))sys.source(file.path(rs_app_dir,'R/server.R'),envir=.GlobalEnv)
check<-function(ok,msg){if(!isTRUE(ok))stop('FAIL: ',msg);cat('PASS:',msg,'\n')}
check(exists('rs_server'),'Shiny server is implemented')
shiny::testServer(rs_server,{
  session$setInputs(load_demo=1)
  check(rv$p$synthetic && nrow(rv$p$records)==8,'demo loads eight synthetic acquisition records')
  session$setInputs(run_analysis=1)
  check(!is.null(rv$p$fit),'UI run action executes real analysis')
  fit<-rv$p$fit;first<-results()$Preview_EI
  session$setInputs(threshold_change=list(value=20,source='slider',nonce=1))
  check(rv$p$threshold==.2 && identical(rv$p$fit,fit),'UI slider updates threshold without refitting')
  check(!identical(results()$Preview_EI,first),'UI slider recalculates EI')
  session$setInputs(reset_threshold=1)
  check(rv$p$threshold==.03,'UI reset returns to 3 percent')
  session$setInputs(plate_selection=c('A01','A02'))
  check(identical(rv$selected,c('A01','A02')),'plate selection reaches server')
  session$setInputs(plate_selection='A01',open_group=1)
  session$setInputs(confirm_group=list(group='Synthetic cohort B'))
  check(rv$p$plate$Group[1]=='Synthetic cohort B' && identical(rv$p$fit,fit),'group edit changes display without model refit')
  fresh<-new_project();fresh$reference<-parse_fasta('>DIFFERENT.1\nACGTACGT');refresh(fresh)
  check(is.null(rv$amplicon) && is.null(rv$candidates),'project replacement clears previous primer drafts')
})
cat('SERVER SUITE PASS\n')
