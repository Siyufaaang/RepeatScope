source('development/shiny_app/R/bootstrap.R');require_dependencies()
check<-function(ok,msg){if(!isTRUE(ok))stop('FAIL: ',msg,call.=FALSE);cat('PASS:',msg,'\n')}
rejected<-function(p)inherits(try(validate_project(p),silent=TRUE),'try-error')
p<-new_project()
bad<-p;attr(bad$plate,'metadata')<-new.env(parent=emptyenv())
check(rejected(bad),'environment-valued attributes are rejected before schema inspection')
bad<-p;attr(bad$plate,'metadata')<-list(nested=new.env(parent=emptyenv()))
check(rejected(bad),'nested attribute objects cannot bypass structural validation')
bad<-p;bad$plate<-structure(new.env(parent=emptyenv()),class='data.frame')
check(rejected(bad),'classed environments are not treated as ordinary data frames')
bad<-p;bad$plate<-structure(unclass(p$plate),class=c('unrecognized_frame','data.frame'))
check(rejected(bad),'unrecognized dispatch classes are rejected')
validate_project(p)
p<-fit_project(synthetic_project());validate_project(p)
saved<-tempfile(fileext='.rds');save_project(p,saved)
check(identical(p,read_project(saved)),'ordinary fitted synthetic projects still round-trip exactly')
unlink(saved)
cat('PROJECT STRUCTURAL VALIDATION PASS\n')
