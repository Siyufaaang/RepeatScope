source('development/shiny_app/tests/helper.R');load_module('reference')
check(exists('locate_amplicon'),'reference engine is implemented')
check(reverse_complement('ACGTTGCA')=='TGCAACGT','reverse primer uses reverse complement')
seq<-paste0('TTATGCGA','CAGCAGCAGCAACAGCAG','TTGACCGT')
s<-locate_amplicon(seq,'GGTTATGCGA','CCACGGTCAA',forward_tail='GG',reverse_tail='CC')
check(s$status=='located' && s$start==1 && s$end==34 && s$expected_bp==38,'tails extend actual product without shifting binding coordinates')
c<-repeat_candidates(seq,'CAG')
check(any(c$Start==9 & c$End==26),'interrupted tract is suggested with phase-aware coordinates')
z<-confirm_structure(s,9,26,'tract_length','Synthetic counting rule includes CAA','Synthetic manual boundary check')
check(z$fixed_bp==20 && z$counted_bp==18 && z$repeat_units==6,'interruption-aware theoretical length counts target tract once')
# Binding primer overlaps first repeat unit: subtract the tract once, not the primer twice.
o<-locate_amplicon(seq,'TTATGCGACAG','ACGGTCAA')
z<-confirm_structure(o,9,26,'tract_length','Synthetic counting rule includes CAA','Overlap checked')
check(z$fixed_bp==16 && z$forward_overlap==3,'primer-repeat overlap is included exactly once')
check(fails(confirm_structure(o,1,40,'tract_length','rule','reason')),'partially covered tract cannot be confirmed')
multi<-locate_amplicon(paste0(seq,'AAAA',seq),'TTATGCGA','ACGGTCAA')
check(multi$status=='ambiguous','multiple binding sites remain draft')
bad<-locate_amplicon(seq,'TTATGCGT','ACGGTCAA')
check(bad$status=='unsupported','mismatch and partial match do not become confirmed')
rev<-locate_amplicon(reverse_complement(seq),'TTATGCGA','ACGGTCAA')
check(rev$status=='located' && rev$strand==-1,'reverse-oriented reference preserves strand')
check(fails(parse_fasta('>a\nACGT\n>b\nTTTT')),'multiple FASTA records require explicit selection')
check(parse_fasta('>SYNTHETIC.1\nACGT')$accession=='SYNTHETIC.1','offline reference identity is preserved')
for(n in c(17,18)) {
  x<-paste0('TTATGCGA',paste(rep('CAG',n),collapse=''),'TTGACCGT')
  a<-locate_amplicon(x,'TTATGCGA','ACGGTCAA');cc<-confirm_structure(a,9,8+3*n,'tract_length','Synthetic only','checked')
  check(cc$repeat_units==n && cc$fixed_bp==16,paste('synthetic',n,'allele structure; not biological resolution validation'))
}
