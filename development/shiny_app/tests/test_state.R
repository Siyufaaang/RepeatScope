source('development/shiny_app/tests/helper.R')
check(exists('new_project'), 'project state is implemented')
p <- new_project()
check(nrow(p$plate)==96 && p$plate$Well[1]=='A01' && tail(p$plate$Well,1)=='H12','96 coordinates in row-major order')
m <- matrix('',8,12); m[1,1]<-'001';m[8,12]<-'water'; m[2,1]<-'001'
plate <- plate_from_matrix(m)
check(identical(plate$Code[c(1,13,96)],c('001','001','water')), 'plate IDs preserve leading zeros and orientation')
check(all(plate$Role=='unlabelled'), 'blank and legacy water remain unlabelled until reviewed')
labelled <- rbind(c('',as.character(1:12)),cbind(LETTERS[1:8],m))
check(identical(plate$Code,plate_from_matrix(labelled)$Code), 'labelled Excel matrix keeps coordinates')
check(fails(plate_from_matrix(matrix('',4,12))), '48 layout is not guessed')
p$plate<-plate
raw <- data.frame(W=c('A1','A01','A01','H12'),A=c('run1','run2','run2','run1'),S=c('200','200','203','bad'),H=c('1000','900','30','20'),Area='99',ID=c('x','y','z','q'))
im<-normalize_peaks(raw,list(Well='W',Acquisition='A',Size='S',Height='H',Peak_ID='ID'))
check(nrow(im$peaks)==3 && nrow(im$issues)==1,'invalid rows retained in import issue audit')
check(length(unique(im$peaks$Record_ID))==2 && length(unique(im$peaks$Peak_ID))==3,'multiple injections and physical IDs remain separate')
check(fails(normalize_peaks(raw,list(Well='W',Acquisition='A',Size='S',Height='Area'))),'Area is never used as Height')
p$peaks<-im$peaks;p<-sync_records(p)
check(nrow(p$records)==4 && sum(p$records$Well=='A01')==2 && 'water'%in%p$records$Code,'records preserve injections and all mapped IDs including unknown water')
check(nrow(duplicate_records(p))==3,'duplicate ID/acquisition review lists all affected records')
check(fails(apply_roles(p,'A01','unused_empty',confirm=FALSE)),'role overwrite requires affected-well confirmation')
q<-apply_roles(p,'A01','unused_empty',confirm=TRUE)
check('A01'%in%role_conflicts(q)$Well && nrow(q$peaks)==3,'NA peak conflict does not erase data')
check(identical(undo_plate(q)$plate,p$plate),'undo restores roles')
q<-set_groups(p,c('A01','B01'),'Group 1');q<-set_groups(q,'A01','Group 1',toggle=TRUE)
check(q$plate$Group[q$plate$Well=='A01']=='' && q$plate$Group[q$plate$Well=='B01']=='Group 1','edit-mode click toggles only current group')
h<-analysis_fingerprint(p);p$plate$Full_name[1]<-'Long name';p$plate$Group[1]<-'report group'
check(identical(h,analysis_fingerprint(p)),'display names and report groups do not invalidate fits')
p$peaks$Height[1]<-99
check(!identical(h,analysis_fingerprint(p)),'peak changes invalidate fit fingerprint')
cat('STATE SUITE PASS\n')
