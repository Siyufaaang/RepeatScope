source('development/shiny_app/R/bootstrap.R');require_dependencies();library(shiny)
sys.source(file.path(rs_app_dir,'R/server.R'),envir=.GlobalEnv)
check<-function(ok,msg){if(!isTRUE(ok))stop('FAIL: ',msg);cat('PASS:',msg,'\n')}
upload<-function(name) {path<-file.path(rs_app_dir,'examples',name);list(name=name,datapath=path,size=file.info(path)$size,type='application/octet-stream')}
shiny::testServer(rs_server,{
  session$setInputs(load_demo=1)
  session$setInputs(plate_file=upload('SYNTHETIC_plate.xlsx'),plate_sheet='Plate',plate_range='A1:M9',transpose_plate=FALSE,preview_plate=1)
  check(rv$plate_preview$Code[1]=='001' && rv$plate_preview$Code[13]=='005','uploaded Excel preview preserves orientation and leading zero')
  session$setInputs(commit_plate=1)
  check(rv$p$plate$Role[1]=='unlabelled','plate import leaves well roles unconfirmed')
  session$setInputs(peak_file=upload('SYNTHETIC_peaks.csv'),peak_range='',preview_peaks=1)
  mapping<-suggest_mapping(names(rv$raw_peaks));do.call(session$setInputs,setNames(mapping,paste0('map_',names(mapping))))
  session$setInputs(well_from_filename=FALSE,commit_peaks=1)
  check(nrow(rv$p$peaks)==168 && nrow(rv$p$records)==8,'column-mapped CSV upload executes through Shiny import handler')
  session$setInputs(metadata_file=upload('SYNTHETIC_metadata.csv'),import_metadata=1)
  check(rv$p$records$Code[1]=='001' && rv$p$records$QC_status[6]=='unknown','metadata upload retains text identifiers and unconfirmed QC')
  session$setInputs(reference_type='genomic',gene='SYNTHETIC',organism='Synthetic sequence',fasta_file=upload('SYNTHETIC_reference.fasta'),use_fasta=1)
  check(rv$p$reference$accession=='SYNTHETIC.1' && is.null(rv$p$structure),'offline FASTA import resets prior structure confirmation')
  session$setInputs(forward='TTATGCGA',reverse='ACGGTCAA',forward_tail='',reverse_tail='',dye='',motif='CAG',locate_primers=1)
  check(rv$amplicon$status=='located','primer action locates actual forward and reverse sequences')
  draft_path<-tempfile(fileext='.rds');save_project(rv$p,draft_path);draft<-read_project(draft_path);unlink(draft_path)
  check(is.null(draft$structure) && draft$reference_draft$amplicon$forward=='TTATGCGA','unconfirmed primer localization survives project save without becoming confirmed')
  session$setInputs(tract_start=9,tract_end=59,counting_rule='tract_length',counting_basis='Synthetic tract definition',boundary_reason='Synthetic exact sequence',confirm_structure=1)
  check(rv$p$structure$repeat_units==17 && rv$p$structure$fixed_bp==16,'structure confirmation retains counted and fixed length decomposition')
  a<-synthetic_project()$assay
  session$setInputs(assay_name=a$name,assay_source=a$source,assay_scope=a$validation_scope,fixed_bp=16,minimum_bp=0,target_channel='B',nominal_spacing=3,spacing_low=2.5,spacing_high=3.2,tolerance=.8,seed_rfu=100,seed_fraction=.03,predictive_level=.95,search_upper=NA_real_,repeat_bp=3,
    disease_ranges=paste(capture.output(write.csv(a$ranges,row.names=FALSE)),collapse='\n'),include_intermediate=FALSE,assay_confirmed=TRUE,save_assay=1)
  check(rv$p$assay$status=='configured','evidenced synthetic assay can be configured through UI handler')
  session$setInputs(run_analysis=1,threshold_change=list(value=20,source='number',nonce=1),window='extended')
  check(!is.null(rv$p$fit) && rv$p$threshold==.2,'imported data executes fit and current threshold filtering')
  fit<-rv$p$fit
  session$setInputs(plate_selection='A01',batch_role='unused_empty',apply_role=1)
  check(rv$p$plate$Role[1]=='sample','batch-role preview does not modify roles before confirmation')
  session$setInputs(confirm_role=1)
  check(nrow(role_conflicts(rv$p))==1 && nrow(rv$p$peaks)==168,'NA/peak conflict retains all physical input rows')
  session$setInputs(undo_plate=1)
  check(rv$p$plate$Role[1]=='sample' && identical(rv$p$fit,fit),'undo restores role without refitting')
  path<-tempfile(fileext='.repeatscope.rds');save_project(rv$p,path);saved<-rv$p
  session$setInputs(load_demo=2)
  session$setInputs(project_file=list(name='workflow.repeatscope.rds',datapath=path,size=file.info(path)$size),restore_project=1)
  check(identical(rv$p$fit,saved$fit) && rv$p$threshold==.2 && rv$p$window=='extended','project upload handler restores fitted state and current view')
  unlink(path)
})
cat('WORKFLOW INTEGRATION PASS (Shiny server handlers; not browser file-picker verification).\n')
