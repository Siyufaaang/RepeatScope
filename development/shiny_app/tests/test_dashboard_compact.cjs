const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const c={Shiny:{addCustomMessageHandler(){}}};vm.createContext(c);
vm.runInContext(fs.readFileSync('development/shiny_app/www/dashboard.js','utf8'),c);
assert.equal(typeof c.dashboardTileSummary,'function');
const record={kind:'intermediate',allele:'intermediate-1',a:.9140857,b:1.125,a_status:'calculated',b_status:'calculated'};
const well={role:'sample',acquired:true,recordList:[record]};
assert.equal(c.dashboardTileSummary(well,'a').value,'0.914');
assert.equal(c.dashboardTileSummary(well,'b').value,'1.125');
assert.equal(c.dashboardTileSummary({...well,recordList:[{...record,a:0}]},'a').value,'0.000');
const normal={kind:'normal',a:null,b:null,a_status:'not_applicable_normal',b_status:'not_applicable_normal'};
assert.equal(c.dashboardTileSummary({...well,recordList:[normal]},'a').value,'Normal');
assert.equal(c.dashboardTileSummary({...well,recordList:[normal,record]},'a').value,'0.914');
assert.equal(c.dashboardTileSummary({...well,recordList:[record,{...record,allele:'intermediate-2',a:2}]},'a').count,2);
assert.equal(c.dashboardTileSummary({...well,recordList:[{...record,a:null,a_status:'target_ambiguous'}]},'a').value,'Review');
assert.equal(c.dashboardTileSummary(well,'a',true).value,'Rerun');
assert.equal(c.dashboardTileSummary({...well,role:'ce_fill'},'a').value,'');
const html=fs.readFileSync('development/shiny_app/www/dashboard.html','utf8');
assert.match(html,/<section[^>]*data-comparisons/,'method and group comparison is permanently visible');
assert.doesNotMatch(html,/<details[^>]*data-comparisons/);
