source('development/shiny_app/tests/helper.R');load_module('reference');load_module('workflow');load_module('synthetic')
check(exists('amplicon_candidates'),'amplicon-scoped candidate search exists')
seq<-paste0('CAGCAGAAAA','TTATGCGA',paste(rep('CAG',6),collapse=''),'TTGACCGT','AAAACAGCAGCAG')
a<-locate_amplicon(seq,'TTATGCGA','ACGGTCAA');z<-amplicon_candidates(a,'CAG')
check(nrow(z)>0 && all(z$Start>=a$start & z$End<=a$end),'outside repeats never appear in the target table')
check(any(z$Start==19 & z$End==36),'scoped search preserves oriented reference coordinates')
s<-preview_structure(a,z,'CAG')
check(s$status=='preview' && grepl('UNCONFIRMED',structure_svg(s)),'located primers immediately produce a labelled unconfirmed structure')
p<-new_project();check(!workflow_ready(p,1)$ready,'empty project cannot advance past plate import')
p<-synthetic_project();p$workflow<-list(plate_imported=TRUE)
check(workflow_ready(p,1)$ready && workflow_ready(p,2)$ready,'imported layout can advance without a review checkbox')
p$workflow$layout_hash<-object_hash(p$plate)
check(workflow_ready(p,2)$ready && workflow_ready(p,3)$ready,'reviewed layout and real peaks unlock their steps')
p$plate$Group[1]<-'Changed';check(workflow_ready(p,2)$ready,'layout edits do not require a second review step')
check(workflow_ready(p,4)$ready,'confirmed synthetic reference is usable')
p$reference_draft<-list(amplicon=a,suggestions=z);p['structure']<-list(NULL)
check(workflow_ready(p,4)$ready && is.null(p$structure),'combined page accepts a valid unconfirmed draft')
check(exists('project_structure_view'),'saved drafts have a reusable preview view')
p$reference_draft$start<-19L;p$reference_draft$end<-36L;p$reference_draft$counting_rule<-'motif_only'
v<-project_structure_view(p)
check(v$status=='preview' && v$counting_rule=='motif_only','saved preview uses the selected counting rule without confirming it')
tmp<-tempfile(fileext='.rds');save_project(p,tmp);restored<-read_project(tmp);unlink(tmp)
check(identical(project_structure_view(restored),v),'project restore preserves the exact draft preview')
check(!is.null(analysis_manifest(p)$reference_draft),'manifest preserves the unconfirmed draft separately')
p$reference_draft$end<-37L
check(!workflow_ready(p,4)$ready,'invalid edited tract blocks the combined page from advancing')
a2<-locate_amplicon(paste0('TTATGCGA',paste(rep('CAG',13),collapse=''),'CAA',paste(rep('CAG',9),collapse=''),'TTGACCGT'),'TTATGCGA','ACGGTCAA')
s2<-preview_structure(a2,amplicon_candidates(a2,'CAG'),'CAG')
check(s2$repeat_pattern=='(CAG)13 CAA (CAG)9','structure shows actual reference blocks rather than calling CAA a CAG')
check(grepl('(CAG)13 CAA (CAG)9',structure_svg(s2),fixed=TRUE),'actual interrupted structure appears in the exported diagram')
check(grepl('3′ AACTGGCA 5′',structure_svg(s2),fixed=TRUE),'reverse primer reads 3′ to 5′ along the amplicon')
cat('GUIDED SUITE PASS\n')
